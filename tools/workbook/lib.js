// Shared by the workbook builds (tools/history/build.js, tools/computer/build.js):
// load a data folder, check it, and write a page from head.html + data + engine.js + tail.html.
const fs = require('fs'), path = require('path'), vm = require('vm');
const HERE = __dirname, ROOT = path.join(HERE, '..', '..') + '/';
const hash = s => { let h = 5381; for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0; return 'q' + (h >>> 0).toString(36); };
const fail = m => { console.error('build stopped: ' + m); process.exit(1); };

/** Run every .js file in `dir`, in name order, in one context. `start` seeds it (e.g. empty LESSONS/QB
    for data files that only push). `onFile(name, ctx)` runs before each file. */
function loadData(dir, start, onFile){
  const ctx = Object.assign({}, start || {}); vm.createContext(ctx);
  fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort().forEach(f => {
    if (onFile) onFile(f, ctx);
    vm.runInContext(fs.readFileSync(path.join(dir, f), 'utf8').replace(/^const (\w+)/gm, 'var $1'), ctx, { filename: f });
  });
  return ctx;
}

/** Stop the build on anything the app would show wrongly. */
function check(LESSONS, QB){
  const byId = new Map(LESSONS.map(l => [l.id, l]));
  if (byId.size !== LESSONS.length) fail('two lessons share an id');
  const seen = new Set();
  QB.forEach(r => {
    if (!byId.has(r[0])) fail('question for unknown lesson ' + r[0] + ': ' + r[1]);
    if (!Array.isArray(r[2]) || r[2].length !== 4 || new Set(r[2].map(o => String(o).trim().toLowerCase())).size !== 4) fail('needs 4 different options: ' + r[1]);
    const h = hash(r[1]); if (seen.has(h)) fail('two questions have the same text: ' + r[1]); seen.add(h);
  });
  LESSONS.forEach(l => {
    (l.sum || []).forEach(s => { if (/<\/?[a-z]/i.test(s)) fail(l.id + ' summary lines are plain text, shown as typed (no HTML tags): ' + s); });
    l.blocks.forEach(b => {
      if (b.k === 'table') b.rows.forEach(r => { if (r.length !== b.head.length) fail(l.id + ' table "' + b.title + '" has a row with ' + r.length + ' cells, not ' + b.head.length); });
      if (b.k === 'facts' || b.k === 'tl') b.rows.forEach(r => { if (r.length !== 2) fail(l.id + ' "' + b.title + '" has a row without exactly 2 cells'); });
    });
  });
  return byId;
}

