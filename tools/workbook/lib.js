const LABEL = { learn: 'Learn', practice: 'Practice', mock: 'Mock', revise: 'Revise', plan: 'Plan', start: 'Start here', lab: 'Lab' };
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');
const J = v => JSON.stringify(v === undefined ? null : v).replace(/<\//g, '<\\/');      // never close the <script> early
const list = (name, arr) => `const ${name} = [\n${(arr || []).map(J).join(',\n')}\n];\n`;

/** Write one page. `page` = {file, title, brand, small, tabs, source, extra, visual}; `d` = the data consts.
    `visual`: load study-visual.js (photos, maps, charts; and study-world.js too when visual is "world"); d.VIS sets it up.
    `extra` (optional): the page's own script — e.g. Chemistry's Lab tab — put after the data and before the engine,
    so the engine finds its render<Tab>() when it boots. It may use the engine's helpers when it runs. */
function writePage(page, d){
  const read = f => fs.readFileSync(path.join(HERE, f), 'utf8');
  const nav = page.tabs.map(t => `    <button type="button" id="nav-${t}" data-tab="${t}"><svg viewBox="0 0 24 24">${ICON[t]}</svg><span>${LABEL[t]}</span></button>`).join('\n');
  const top = read('head.html').replace('{{TITLE}}', esc(page.title)).replace('{{BRAND}}', esc(page.brand || page.title))
    .replace('{{SMALL}}', esc(page.small)).replace('{{NAV}}', nav);
  const block = `const APP = ${J(d.APP)};\n` + list('GROUPS', d.GROUPS) + list('LESSONS', d.LESSONS) + list('QB', d.QB) +
    list('TIMELINE', d.TIMELINE) + list('LASTMOMENT', d.LASTMOMENT) + list('TILES', d.TILES) +
    `const ERANOTE = ${J(d.ERANOTE || {})};\nconst INTROS = ${J(d.INTROS || {})};\nconst HEATMAP = ${J(d.HEATMAP || null)};\n` +
    (d.VIS ? `const VIS = ${J(d.VIS)};\n` : '');
  const vis = page.visual ? '<script src="study-visual.js?v=00000000"></script>\n' + (page.visual === 'world' ? '<script src="study-world.js?v=00000000"></script>\n' : '') : '';
  const html = top + vis + `<script>\n"use strict";\n/* data: generated by ${page.source} — edit there, not here */\n` + block +
    '</script>\n\n' + (page.extra ? '<script>\n"use strict";\n' + page.extra + '\n</script>\n\n' : '') +
    '<script>\n"use strict";\n' + read('engine.js') + '\n</script>\n' + read('tail.html');
  fs.writeFileSync(ROOT + page.file, html);
  return html.length;
}

/** An app's pictures: run its visual.js (if there is one) with place() and VISUAL, against the app's lessons.
    place(lessonId, where, ...blocks) puts blocks into a lesson: where = 'start', 'end', 'story' (after the story block),
    or the start of a block's title (after that block). visual.js may set VISUAL = { mode: true | 'world', VIS: {...} }.
    Returns { visual, VIS } for writePage, or {} when the app has no visual.js. */
function applyVisual(file, LESSONS, extra){
  if (!fs.existsSync(file)) return {};
  const byId = new Map(LESSONS.map(l => [l.id, l]));
  const place = (id, where, ...blocks) => {
    const l = byId.get(id); if (!l) fail(path.basename(file) + ': no lesson ' + id);
    let at;
    if (where === 'start') at = 0;
    else if (where === 'end') at = l.blocks.length;
    else if (where === 'story') { const k = l.blocks.findIndex(b => b.k === 'story'); at = (k < 0 ? 0 : k) + 1; }
    else { const k = l.blocks.findIndex(b => b.title && String(b.title).replace(/<[^>]+>/g, '').startsWith(where)); if (k < 0) fail(path.basename(file) + ': ' + id + ' has no block titled "' + where + '"'); at = k + 1; }
    l.blocks.splice(at, 0, ...blocks);
  };
  // rows(id, title): a table's (or facts list's) rows as plain text, to build pictures from the lesson's own data
  const strip = s => String(s == null ? '' : s).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').trim();
  const rows = (id, title) => { const l = byId.get(id), b = l && l.blocks.find(b => b.rows && b.title && strip(b.title).startsWith(title));
    if (!b) fail(path.basename(file) + ': ' + id + ' has no table "' + title + '"'); return b.rows.map(r => r.map(strip)); };
  const ctx = Object.assign({ place, rows, LESSONS, VISUAL: null, fail, GEO: require('./geo.js') }, extra || {}); vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(file, 'utf8').replace(/^const (\w+)/gm, 'var $1'), ctx, { filename: file });
  return ctx.VISUAL ? { visual: ctx.VISUAL.mode || true, VIS: ctx.VISUAL.VIS || null } : {};
}

module.exports = { hash, fail, loadData, check, writePage, applyVisual, ROOT };
